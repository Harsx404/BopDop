// Builds BopDop's launcher icons (Android vector drawables) and the brand images used by the
// README from one source: the "play b" mark in docs/brand. Run from the project folder:
//   node tools/brand/build-brand.cjs [path/to/sharp]
// sharp is only needed for the PNGs; without it just the vectors and SVGs are written.
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..', '..');
const brand = path.join(root, 'docs', 'brand');
const drawable = path.join(root, 'app', 'src', 'main', 'res', 'drawable');

// The mark, in its own 320 x 320 design space (as delivered, drawn at translate(32 20)).
const GLYPH = 'M60 16H84C97.255 16 108 26.745 108 40V78.13C114.446 76.734 121.138 76 128 76C179.915 76 222 118.085 222 170C222 221.915 179.915 264 128 264C76.085 264 34 221.915 34 170V42C34 27.641 45.641 16 60 16Z M109 126L172 162Q184 169 172 176L109 212Q100 217 100 206V132Q100 121 109 126Z';
// The outline alone (no play cut-out), for clipping the gloss.
const OUTLINE = GLYPH.split(' M109')[0];

/** [OUTLINE] moved down by [dy] (absolute M/H/V/C commands only, as drawn). */
function shifted(d, dy) {
  const out = [];
  let cmd = '';
  let i = 0;
  for (const tok of d.match(/[A-Za-z]|-?[\d.]+/g)) {
    if (/[A-Za-z]/.test(tok)) { cmd = tok; i = 0; out.push(tok); continue; }
    const n = parseFloat(tok);
    const isY = cmd === 'V' || ((cmd === 'M' || cmd === 'C' || cmd === 'L') && i % 2 === 1);
    out.push(isY ? +(n + dy).toFixed(3) : n);
    i++;
  }
  return out.join(' ').replace(/ ([A-Za-z]) /g, '$1').replace(/^([A-Za-z]) /, '$1');
}
// The shadow is the part of the moved-down outline that sticks out below the mark: the two
// outlines together, even-odd, so nothing shows through the play cut-out.
const SHADOW = shifted(OUTLINE, 7) + ' ' + OUTLINE;

// Adaptive icons are 108 units; the launcher mask may cut anything outside the middle 66.
// The mark's box (188 x 248 around 160,160) is scaled to sit inside that safe circle.
const S = 0.205;
const T = 54 - 160 * S;

// --- looks ----------------------------------------------------------------------------------
// Each look: tile gradient, a soft glow behind the bowl, the sheen across the top, and the mark.
const LOOKS = {
  classic: {
    tile: ['#2C2C31', '#0E0E10'], glow: '#FF4D2D', glowAlpha: 0.38, sheen: 0.07,
    mark: ['#FF9466', '#FF4D2D', '#E0331A'], gloss: 0.55, shadow: 0.45,
  },
  orange: {
    tile: ['#FF7A4A', '#E0331A'], glow: '#FFFFFF', glowAlpha: 0.22, sheen: 0.16,
    mark: ['#FFFFFF', '#FFF4EF', '#FFE1D6'], gloss: 0.7, shadow: 0.28,
  },
  light: {
    tile: ['#FFFFFF', '#E7E8EE'], glow: '#FF4D2D', glowAlpha: 0.14, sheen: 0.5,
    mark: ['#FF9466', '#FF4D2D', '#E0331A'], gloss: 0.55, shadow: 0.22,
  },
};

const hex = (c, a = 1) => '#' + Math.round(a * 255).toString(16).padStart(2, '0').toUpperCase() + c.slice(1).toUpperCase();

// --- Android vector drawables ---------------------------------------------------------------
const NS = 'xmlns:android="http://schemas.android.com/apk/res/android"\n    xmlns:aapt="http://schemas.android.com/aapt"';
const vec = (body, note) => `<?xml version="1.0" encoding="utf-8"?>
<!-- ${note} Generated by tools/brand/build-brand.cjs. -->
<vector ${NS}
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
${body}</vector>
`;
const linear = (x1, y1, x2, y2, stops) => `
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="${x1}" android:startY="${y1}" android:endX="${x2}" android:endY="${y2}">
${stops.map(([o, c]) => `                <item android:offset="${o}" android:color="${c}" />`).join('\n')}
            </gradient>
        </aapt:attr>
    `;
const radial = (cx, cy, r, stops) => `
        <aapt:attr name="android:fillColor">
            <gradient android:type="radial" android:centerX="${cx}" android:centerY="${cy}" android:gradientRadius="${r}">
${stops.map(([o, c]) => `                <item android:offset="${o}" android:color="${c}" />`).join('\n')}
            </gradient>
        </aapt:attr>
    `;

function androidBackground(l) {
  return vec(`    <path android:pathData="M0,0h108v108h-108z">${linear(0, 0, 108, 108, [[0, hex(l.tile[0])], [1, hex(l.tile[1])]])}</path>
    <path android:pathData="M0,0h108v108h-108z">${radial(54, 62, 46, [[0, hex(l.glow, l.glowAlpha)], [1, hex(l.glow, 0)]])}</path>
    <path android:pathData="M-10,24 C30,6 70,46 118,28 L118,-10 L-10,-10 Z" android:fillColor="${hex('#FFFFFF', l.sheen)}" />
`, 'Launcher tile: glass over a soft glow.');
}

function androidForeground(l) {
  const m = l.mark;
  return vec(`    <group android:scaleX="${S}" android:scaleY="${S}" android:translateX="${T.toFixed(2)}" android:translateY="${T.toFixed(2)}">
        <group android:translateX="32" android:translateY="20">
            <!-- Shadow, so the mark floats above the tile. -->
            <path android:fillType="evenOdd" android:fillColor="${hex('#000000', l.shadow)}"
                android:pathData="${SHADOW}" />
            <path android:fillType="evenOdd" android:pathData="${GLYPH}">${linear(0, 16, 0, 264, [[0, hex(m[0])], [0.5, hex(m[1])], [1, hex(m[2])]]).replace(/\n {8}/g, '\n                ')}</path>
            <!-- Gloss across the top, clipped to the mark; it fades out above the play cut-out. -->
            <group>
                <clip-path android:pathData="${OUTLINE}" />
                <path android:pathData="M0,0 H260 V122 H0 Z">${linear(0, 16, 0, 122, [[0, hex('#FFFFFF', l.gloss)], [1, hex('#FFFFFF', 0)]]).replace(/\n {8}/g, '\n                    ')}</path>
            </group>
        </group>
    </group>
`, 'The play b, glassy.');
}

const MONO = vec(`    <group android:scaleX="${S}" android:scaleY="${S}" android:translateX="${T.toFixed(2)}" android:translateY="${T.toFixed(2)}">
        <group android:translateX="32" android:translateY="20">
            <path android:fillType="evenOdd" android:fillColor="#FF000000" android:pathData="${GLYPH}" />
        </group>
    </group>
`, 'Themed-icon silhouette: the play b.');

// --- SVG versions (same geometry) for the README and brand folder -----------------------------
function svgIcon(l, { rounded = true, size = 108 } = {}) {
  const m = l.mark;
  const mask = rounded ? `<clipPath id="tile"><rect width="108" height="108" rx="24"/></clipPath>` : '';
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="${size}" height="${size}">
<defs>${mask}
<linearGradient id="t" x1="0" y1="0" x2="108" y2="108" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="${l.tile[0]}"/><stop offset="1" stop-color="${l.tile[1]}"/></linearGradient>
<radialGradient id="g" cx="54" cy="62" r="46" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="${l.glow}" stop-opacity="${l.glowAlpha}"/><stop offset="1" stop-color="${l.glow}" stop-opacity="0"/></radialGradient>
<linearGradient id="m" x1="0" y1="16" x2="0" y2="264" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="${m[0]}"/><stop offset="0.5" stop-color="${m[1]}"/><stop offset="1" stop-color="${m[2]}"/></linearGradient>
<linearGradient id="s" x1="0" y1="16" x2="0" y2="122" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="#FFFFFF" stop-opacity="${l.gloss}"/><stop offset="1" stop-color="#FFFFFF" stop-opacity="0"/></linearGradient>
<clipPath id="o"><path d="${OUTLINE}"/></clipPath>
</defs>
<g${rounded ? ' clip-path="url(#tile)"' : ''}>
<rect width="108" height="108" fill="url(#t)"/><rect width="108" height="108" fill="url(#g)"/>
<path d="M-10,24 C30,6 70,46 118,28 L118,-10 L-10,-10 Z" fill="#FFFFFF" fill-opacity="${l.sheen}"/>
<g transform="translate(${T.toFixed(2)} ${T.toFixed(2)}) scale(${S}) translate(32 20)">
<path fill-rule="evenodd" d="${SHADOW}" fill="#000000" fill-opacity="${l.shadow}"/>
<path fill-rule="evenodd" d="${GLYPH}" fill="url(#m)"/>
<g clip-path="url(#o)"><rect x="0" y="0" width="260" height="122" fill="url(#s)"/></g>
</g></g></svg>
`;
}

// The wordmark alone (letters only), from the delivered lockups.
function wordmark(file) {
  const src = fs.readFileSync(path.join(brand, file), 'utf8');
  const letters = src.slice(src.indexOf('<g '), src.lastIndexOf('</g>') + 4);
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="262 92 678 182">${letters}</svg>\n`;
}

async function main() {
  const out = {
    'ic_launcher_bg.xml': androidBackground(LOOKS.classic),
    'ic_launcher_fg.xml': androidForeground(LOOKS.classic),
    'ic_launcher_bg_dark.xml': androidBackground(LOOKS.orange),
    'ic_launcher_fg_dark.xml': androidForeground(LOOKS.orange),
    'ic_launcher_bg_light.xml': androidBackground(LOOKS.light),
    'ic_launcher_fg_light.xml': androidForeground(LOOKS.light),
    'ic_launcher_mono.xml': MONO,
  };
  for (const [f, s] of Object.entries(out)) fs.writeFileSync(path.join(drawable, f), s);

  const svgs = {
    'app-icon-glass.svg': svgIcon(LOOKS.classic),
    'app-icon-orange.svg': svgIcon(LOOKS.orange),
    'app-icon-light.svg': svgIcon(LOOKS.light),
    'wordmark.svg': wordmark('logo.svg'),
    'wordmark-dark.svg': wordmark('logo-dark.svg'),
  };
  for (const [f, s] of Object.entries(svgs)) fs.writeFileSync(path.join(brand, f), s);

  const sharpPath = process.argv[2];
  if (!sharpPath) return console.log('vectors and SVGs written (no sharp given, PNGs skipped)');
  const sharp = require(sharpPath);
  for (const f of ['app-icon-glass', 'app-icon-orange', 'app-icon-light']) {
    await sharp(Buffer.from(svgIcon(LOOKS[f.split('-')[2] === 'glass' ? 'classic' : f.split('-')[2]], { size: 1024 })))
      .png().toFile(path.join(brand, f + '.png'));
  }
  for (const f of ['wordmark', 'wordmark-dark']) {
    await sharp(Buffer.from(svgs[f + '.svg']), { density: 300 }).resize({ width: 1400 }).png().toFile(path.join(brand, f + '.png'));
  }
  console.log('vectors, SVGs and PNGs written');
}
main().catch(e => { console.error(e); process.exitCode = 1; });
