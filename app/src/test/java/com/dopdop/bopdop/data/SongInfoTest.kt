package com.dopdop.bopdop.data

import org.json.JSONObject
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test

class SongInfoTest {
    private val auto = """
        Provided to YouTube by Universal Music Group

        Alfaaz · Hamza Malik · Zain Zohaib

        Alfaaz

        ℗ 2024 Zain Zohaib Records

        Released on: 2024-02-09

        Composer: Zain Zohaib
        Lyricist: Hamza Malik, Zain Zohaib
        Producer: Someone

        Auto-generated by YouTube.
    """.trimIndent()

    @Test fun readsYouTubeAutoGeneratedDescription() {
        val i = SongInfo.fromYtDescription(auto)
        assertEquals("2024-02-09", i.released)
        assertEquals("Alfaaz", i.album)
        assertEquals("Universal Music Group", i.label)
        assertEquals("℗ 2024 Zain Zohaib Records", i.copyright)
        assertEquals(listOf("Composer", "Lyricist", "Producer"), i.credits.map { it.role })
        assertEquals(listOf("Hamza Malik", "Zain Zohaib"), i.credits[1].names)
    }

    @Test fun ignoresFreeFormDescriptions() {
        assertTrue(SongInfo.fromYtDescription("Official video\nFollow us: instagram.com/x\nDirector: Y").isEmpty)
    }

    @Test fun readsJioSaavnSongObject() {
        val s = JSONObject("""
            {"id":"x","language":"hindi","year":"2013","more_info":{"album":"Aashiqui 2","label":"T-Series",
             "release_date":"2013-04-05","copyright_text":"&copy; 2013 T-Series","music":"Mithoon",
             "artistMap":{"artists":[
               {"name":"Arijit Singh","role":"singer"},{"name":"Mithoon","role":"music"},
               {"name":"Mithoon","role":"lyricist"},{"name":"Aditya Roy Kapur","role":"starring"},
               {"name":"Arijit Singh","role":"singer"}]}}}
        """.trimIndent())
        val i = SongInfo.fromSaavn(s)
        assertEquals("2013-04-05", i.released)
        assertEquals("T-Series", i.label)
        assertEquals("Hindi", i.language)
        assertEquals(listOf("Singers", "Music", "Lyrics", "Starring"), i.credits.map { it.role })
        assertEquals(listOf("Arijit Singh"), i.credits[0].names)
    }

    @Test fun fillsGapsWithoutOverwriting() {
        val i = SongInfo(released = "2020").orElse(SongInfo(released = "2019-01-01", label = "L"))
        assertEquals("2020", i.released)
        assertEquals("L", i.label)
    }
}
