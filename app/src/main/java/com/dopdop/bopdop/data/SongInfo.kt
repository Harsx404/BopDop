package com.dopdop.bopdop.data

import com.dopdop.bopdop.data.model.Source
import com.dopdop.bopdop.data.model.Track
import com.dopdop.bopdop.data.net.TtlCache
import com.dopdop.bopdop.data.saavn.SaavnApi
import com.dopdop.bopdop.data.ytm.YtMusic
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import org.json.JSONObject

/** One credit line: "Composer" → ["A. R. Rahman"]. */
data class Credit(val role: String, val names: List<String>)

/** What the song info panel shows beyond the title. Every field is optional: catalogues differ. */
data class SongInfo(
    /** ISO date ("2023-05-12") or just a year. */
    val released: String = "",
    val album: String = "",
    val label: String = "",
    val language: String = "",
    val copyright: String = "",
    val credits: List<Credit> = emptyList(),
) {
    val isEmpty get() = released.isEmpty() && album.isEmpty() && label.isEmpty() && language.isEmpty() && copyright.isEmpty() && credits.isEmpty()

    /** Fill gaps from [other] without overwriting what we already have. */
    fun orElse(other: SongInfo?) = if (other == null) this else SongInfo(
        released = released.ifEmpty { other.released },
        album = album.ifEmpty { other.album },
        label = label.ifEmpty { other.label },
        language = language.ifEmpty { other.language },
        copyright = copyright.ifEmpty { other.copyright },
        credits = credits.ifEmpty { other.credits },
    )

    companion object {
        private val cache = TtlCache<String, SongInfo>(6 * 3600_000L, 80)

        /**
         * YouTube Music's auto-generated description for label uploads:
         * "Provided to YouTube by X ⏎ Song · Artist ⏎ Album ⏎ ℗ 2023 Label ⏎ Released on: 2023-05-12 ⏎ Composer: … ⏎ Auto-generated by YouTube."
         */
        fun fromYtDescription(desc: String): SongInfo {
            // Anything else is a free-form description whose "Follow us: …" lines aren't credits.
            if (!desc.contains("Provided to YouTube by", true) && !desc.contains("Auto-generated by YouTube", true)) return SongInfo()
            val lines = desc.lines().map { it.trim() }
            val provided = lines.firstOrNull { it.startsWith("Provided to YouTube by", true) }?.substringAfter(" by ")?.trim().orEmpty()
            val released = lines.firstNotNullOfOrNull { Regex("^Released on:\\s*(\\d{4}-\\d{2}-\\d{2})").find(it)?.groupValues?.get(1) }.orEmpty()
            val copyright = lines.firstOrNull { it.startsWith("℗") }.orEmpty()
            // The album is the block right after the "Song · Artist" line.
            val songLine = lines.indexOfFirst { it.contains(" · ") }
            val album = if (songLine < 0) "" else lines.drop(songLine + 1).firstOrNull { it.isNotEmpty() }
                ?.takeUnless { it.startsWith("℗") || it.startsWith("Released on", true) || it.contains(':') }.orEmpty()
            val credits = LinkedHashMap<String, MutableList<String>>()
            for (l in lines) {
                val m = Regex("^([\\p{L} &/-]{2,40}):\\s*(.+)$").find(l) ?: continue
                val role = m.groupValues[1].trim()
                if (role.equals("Released on", true) || role.startsWith("Provided", true) || role.startsWith("Auto-generated", true)) continue
                if (role.contains("http", true)) continue
                credits.getOrPut(role) { mutableListOf() }.addAll(m.groupValues[2].split(",").map { it.trim() }.filter { it.isNotEmpty() })
            }
            return SongInfo(
                released = released,
                album = album,
                label = provided,
                copyright = copyright,
                credits = credits.map { (r, n) -> Credit(r, n.distinct()) },
            )
        }

        private val saavnRoles = linkedMapOf("singer" to "Singers", "music" to "Music", "lyricist" to "Lyrics", "starring" to "Starring")

        /** A JioSaavn api_version 4 song object (song.getDetails). */
        fun fromSaavn(s: JSONObject): SongInfo {
            val m = s.optJSONObject("more_info") ?: JSONObject()
            val byRole = LinkedHashMap<String, MutableList<String>>()
            m.optJSONObject("artistMap")?.optJSONArray("artists")?.let { arr ->
                for (i in 0 until arr.length()) {
                    val a = arr.optJSONObject(i) ?: continue
                    val role = saavnRoles[a.optString("role")] ?: continue
                    val name = SaavnApi.unescape(a.optString("name")).trim()
                    if (name.isNotEmpty()) byRole.getOrPut(role) { mutableListOf() }.add(name)
                }
            }
            if ("Music" !in byRole) m.optString("music").takeIf { it.isNotBlank() }?.let { byRole["Music"] = SaavnApi.unescape(it).split(",").map(String::trim).toMutableList() }
            val credits = saavnRoles.values.mapNotNull { r -> byRole[r]?.distinct()?.takeIf { it.isNotEmpty() }?.let { Credit(r, it) } }
            return SongInfo(
                released = m.optString("release_date").takeIf { Regex("^\\d{4}-\\d{2}-\\d{2}$").matches(it) } ?: s.optString("year"),
                album = SaavnApi.unescape(m.optString("album")),
                label = SaavnApi.unescape(m.optString("label")),
                language = s.optString("language").replaceFirstChar { it.uppercase() },
                copyright = SaavnApi.unescape(m.optString("copyright_text")),
                credits = credits,
            )
        }

        /**
         * Song info from the track's own catalogue, topped up from its JioSaavn copy (which knows
         * the label, language and the singers / music / lyrics credits for most Indian releases).
         */
        suspend fun load(t: Track): SongInfo = withContext(Dispatchers.IO) {
            cache.getOrLoad(t.id) {
                when (t.source) {
                    Source.SAAVN -> runCatching { SaavnApi.songObject(t.rawId)?.let(::fromSaavn) }.getOrNull() ?: SongInfo()
                    Source.YTM -> {
                        val own = runCatching { fromYtDescription(YtMusic.description(t.rawId)) }.getOrDefault(SongInfo())
                        val match = if (own.credits.isNotEmpty() && own.released.isNotEmpty()) null
                        else runCatching { SaavnApi.hiResMatch(t.title, t.artist, t.durationSec)?.let { SaavnApi.songObject(it.rawId) }?.let(::fromSaavn) }.getOrNull()
                        // The match may be another cut of the song ("– Vocals", "Lofi"): its album never replaces ours.
                        own.orElse(match).copy(album = own.album.ifEmpty { t.album }.ifEmpty { match?.album.orEmpty() })
                    }
                    Source.LOCAL -> SongInfo()
                }.let { if (it.album.isEmpty() && t.album.isNotBlank()) it.copy(album = t.album) else it }
            }
        }
    }
}
